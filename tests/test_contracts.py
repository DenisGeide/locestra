def test_task_state_accepts_running_complete_and_failed_states():
    running = task_state()
    complete = task_state(
        status="complete",
        artifacts=[artifact()],
        modified_files=["services/example.py"],
        next_action=None,
        updated_at=NOW + timedelta(seconds=10),
    )
    failed = task_state(
        status="failed",
        unresolved_errors=["test suite returned exit code 1"],
        next_action="Inspect the failing test.",
        updated_at=NOW + timedelta(seconds=20),
    )

    assert running.status == "running"
    assert complete.status == "complete"
    assert failed.status == "failed"


