NOW = datetime(2026, 7, 14, 17, 0, tzinfo=timezone.utc)
SHA256 = "a" * 64


def normalized_request(**overrides):
    values = {
        "request_id": "req-001",
        "user_message": "Inspect the repository and report the result.",
        "attachments": [],
        "source": "api",
        "project_hint": r"C:\work\project",
        "explicit_route": None,
        "created_at": NOW,
        "correlation_id": "corr-001",
    }
    values.update(overrides)
    return NormalizedRequestV1(**values)


def artifact(**overrides):
    values = {
        "artifact_id": "artifact-001",
        "type": "report",
        "path": "outputs/report.md",
        "hash": SHA256,
        "producer": "qwen_code",
        "source_request": "req-001",
        "created_at": NOW,
        "provenance": ["generated by task task-001"],
        "retention": RetentionPolicyV1(policy="task", expires_at=None),
    }
    values.update(overrides)
    return ArtifactMetadataV1(**values)


