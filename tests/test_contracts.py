def test_attachment_rejects_inline_data_url_and_content_field():
    inline = {
        "attachment_id": "attachment-001",
        "kind": "image",
        "reference": "data:image/png;base64,AAAA",
        "media_type": "image/png",
        "size_bytes": 4,
        "sha256": SHA256,
        "provenance": [],
    }
    with pytest.raises(ValidationError):
        normalized_request(attachments=[inline])

    inline["reference"] = "inbox/image.png"
    inline["content"] = "AAAA"
    with pytest.raises(ValidationError):
        normalized_request(attachments=[inline])


