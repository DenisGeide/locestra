def test_pydantic_json_schema_is_versioned_machine_source():
    schema = NormalizedRequestV1.model_json_schema()

    assert schema["properties"]["schema_version"]["const"] == "1.0"
    assert {
        "request_id",
        "user_message",
        "attachments",
        "source",
        "project_hint",
        "explicit_route",
        "created_at",
        "correlation_id",
    }.issubset(schema["required"])
